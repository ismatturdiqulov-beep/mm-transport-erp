-- MM Transport ERP — миграция 35: снимок дежурного механика/медработника в путёвке
-- (2026-07-23). Раньше в компании был только один механик и один медработник
-- (WAYBILL_SETTINGS.mechanicName/medicName — одна строка в company_settings,
-- печаталась на КАЖДОЙ путёвке без исключения). Реальный клиент (крупный
-- перевозчик, тестирует по договорённости) держит несколько механиков/
-- медработников посменно — нужно фиксировать, кто именно дежурил на КОНКРЕТНОЙ
-- путёвке, а не только общий список в настройках.
--
-- Текстовый снимок (не ссылка на id) — тот же принцип, что уже применён к
-- truck/trailer/drv1/drv2 в 0013: путёвка это документ на момент времени,
-- печатный бланк не должен задним числом меняться, если список механиков потом
-- отредактируют.
alter table waybills
  add column mechanic_name text,
  add column medic_name    text;
