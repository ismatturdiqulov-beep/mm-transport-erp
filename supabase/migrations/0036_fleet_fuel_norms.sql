-- MM Transport ERP — миграция 36: нормы расхода топлива на ед. ПС
-- (2026-08-04). Реальный сценарий: некоторые тягачи расходуют топливо
-- по-разному гружёными и порожняком — нужна отдельная норма (л/100км) для
-- каждого состояния, чтобы потом сравнивать факт с нормой и ловить перерасход/
-- слив (см. Этапы 3-4 того же решения пользователя). Храним на ед. ПС
-- (fleet), а не на самом тягаче (transport) — именно ПС привязано к рейсу,
-- и норма может отличаться в зависимости от того, с каким прицепом ходит
-- этот тягач (решение пользователя 2026-08-04).
alter table fleet
  add column fuel_norm_loaded numeric,
  add column fuel_norm_empty  numeric;
