-- MM Transport ERP — миграция 37: порожний пробег рейса
-- (2026-08-04). Этап 2 решения пользователя про нормы расхода топлива:
-- диспетчер уже вводит общий пробег (km_start/km_end), но не знает, сколько
-- из него было порожняком (например разгрузился в Самаре, а следующая
-- загрузка — в Казани, путь Самара→Казань идёт без груза). Одно число на
-- весь рейс — вводится при завершении рейса, когда уже известен весь
-- маршрут. Пробег с грузом далее считается как km_end-km_start-empty_km,
-- отдельного поля под него не нужно.
alter table trips add column empty_km numeric;
