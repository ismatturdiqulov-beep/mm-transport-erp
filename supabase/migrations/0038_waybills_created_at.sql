-- MM Transport ERP — миграция 38: время создания записи путёвки
-- (2026-08-04). У ТИР/Дозвол/Кассы/Доверенностей/Трудовых договоров уже есть
-- created_at и он используется для сортировки "новые сверху" (с тай-брейком
-- по времени внутри одного дня) — у waybills такого поля не было вообще,
-- поэтому список путёвок не сортировался осмысленно. Для уже существующих
-- путёвок реальное время создания не восстановить — по решению пользователя
-- 2026-08-04 это не нужно, они просто получат дату миграции по умолчанию;
-- сортировка станет осмысленной для новых путёвок.
alter table waybills add column created_at timestamptz not null default now();
