-- MM Transport ERP — миграция 48: автоочистка служебных сообщений бота
-- (2026-08-11). Бот копил в чате промежуточные вопросы ("Введите тему...",
-- "Что нужно?" и т.п.) — визуальный мусор, реального содержания в них нет
-- после того, как на них ответили. Бот умеет удалять ТОЛЬКО свои же
-- сообщения (ограничение Telegram — сообщения пользователя недоступны для
-- удаления боту в личном чате), поэтому храним id последнего отправленного
-- служебного сообщения и подчищаем его перед следующим шагом.
alter table owner_notify add column pending_prompt_msg_id bigint;
