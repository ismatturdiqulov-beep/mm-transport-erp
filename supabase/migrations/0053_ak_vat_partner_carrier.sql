-- Блок «Ангрен Каолин» — миграция 3: НДС и машины партнёра (2026-11-26).
--
-- Решения владельца:
--   * местные перевозки облагаются НДС 12%, цена завода по ним ВСЕГДА включает НДС;
--     НДС считается отдельно и показывается отдельной строкой «НДС к уплате»;
--     международные — без НДС;
--   * перевозчику-плательщику НДС платим с НДС, неплательщику — без НДС;
--   * у партнёра бывают личные машины (на местных рейсах): заявка оформляется на MM
--     (is_own), а деньги за рейс идут партнёру — это оплата перевозки, не его доля.

alter table ak_carriers
  add column vat_payer   boolean not null default false,
  add column partner_key text check (partner_key in ('ismat', 'sarvar'));

comment on column ak_carriers.vat_payer is 'Плательщик НДС: на местных рейсах платим ему цену с НДС';
comment on column ak_carriers.partner_key is 'Личные машины партнёра: оплата рейса уходит этому партнёру';

-- Ставка НДС в базисных пунктах (1200 = 12%), чтобы не хранить дробь.
insert into ak_settings (key, value) values ('tax', '{"vat_rate_bp": 1200}')
on conflict (key) do nothing;
